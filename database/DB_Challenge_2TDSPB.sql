    T_M_ALTERNATIVA_T_M_PERGUNTA_T_M_CATEGORIA_id_categoria,
    T_M_CATEGORIA_id_categoria
)
SELECT
    SYSDATE,
    u.id_usuario,
    a.id_alternativa,
    a.T_M_PERGUNTA_id_pergunta,
    a.T_M_PERGUNTA_T_M_CATEGORIA_id_categoria,
    a.T_M_PERGUNTA_T_M_CATEGORIA_id_categoria
FROM T_M_USUARIO u
CROSS JOIN T_M_ALTERNATIVA a
JOIN T_M_PERGUNTA p
    ON p.id_pergunta = a.T_M_PERGUNTA_id_pergunta
    AND p.T_M_CATEGORIA_id_categoria = a.T_M_PERGUNTA_T_M_CATEGORIA_id_categoria
WHERE u.nm_email = 'eva@email.com'
AND p.ds_enunciado = 'Qual material e utilizado para proteger contra determinados tipos de radiacao?'
AND a.ds_texto = 'Chumbo';

COMMIT;


SELECT
    u.nm_usuario,
    u.nm_email,
    c.nm_categoria,
    p.ds_enunciado,
    a.ds_texto AS alternativa_escolhida,
    CASE
        WHEN a.ds_correta = 'S' THEN 'Correta'
        ELSE 'Incorreta'
    END AS resultado,
    r.dt_resposta
FROM T_M_RESPOSTA_USUARIO r
INNER JOIN T_M_USUARIO u
    ON r.T_M_USUARIO_id_usuario = u.id_usuario
INNER JOIN T_M_ALTERNATIVA a
    ON r.T_M_ALTERNATIVA_id_alternativa = a.id_alternativa
    AND r.T_M_ALTERNATIVA_T_M_PERGUNTA_id_pergunta =
        a.T_M_PERGUNTA_id_pergunta
    AND r.T_M_ALTERNATIVA_T_M_PERGUNTA_T_M_CATEGORIA_id_categoria =
        a.T_M_PERGUNTA_T_M_CATEGORIA_id_categoria
INNER JOIN T_M_PERGUNTA p
    ON a.T_M_PERGUNTA_id_pergunta = p.id_pergunta
    AND a.T_M_PERGUNTA_T_M_CATEGORIA_id_categoria =
        p.T_M_CATEGORIA_id_categoria
INNER JOIN T_M_CATEGORIA c
    ON p.T_M_CATEGORIA_id_categoria = c.id_categoria
ORDER BY r.dt_resposta;


SELECT
    p.id_pergunta,
    p.ds_enunciado,
    c.nm_categoria,
    a.id_alternativa,
    a.ds_texto,
    a.ds_correta
FROM T_M_PERGUNTA p
INNER JOIN T_M_CATEGORIA c
    ON p.T_M_CATEGORIA_id_categoria = c.id_categoria
INNER JOIN T_M_ALTERNATIVA a
    ON a.T_M_PERGUNTA_id_pergunta = p.id_pergunta
    AND a.T_M_PERGUNTA_T_M_CATEGORIA_id_categoria = c.id_categoria
ORDER BY
    p.id_pergunta,
    a.id_alternativa;


